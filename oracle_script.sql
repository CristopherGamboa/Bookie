-- Table for managing Users
CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    DOCUMENT_ID VARCHAR2(20) UNIQUE NOT NULL, -- Reemplaza al RUT
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE
);

-- Table for managing Book Loans
CREATE TABLE LOANS (
    LOAN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    BOOK_TITLE VARCHAR2(200) NOT NULL,
    LOAN_DATE DATE DEFAULT SYSDATE,
    RETURN_DATE DATE,
    STATUS VARCHAR2(50) DEFAULT 'BORROWED',
    CONSTRAINT FK_LOAN_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);